import BelloCore
import Foundation

// The merge-request panel's on-demand reads and the person's own GitLab actions (docs/features/gitlab.md). Writes are
// gated per instance (Settings ▸ GitLab, off by default) and by the token's scopes when GitLab reports them; approve
// and merge have their own switch and send the SHA the person saw. Agents never reach approve or merge.

extension MergeRequestService {
    /// Bytes of a job log the viewer loads (the end of the log).
    public static let jobLogBytes = 512 << 10

    public func forgeProject(_ ref: MergeRequestRef) throws -> ForgeProject {
        guard let instance = instances.first(where: { $0.baseURL == ref.instance }) ?? GitLabInstance(baseURL: ref.instance),
            instances.contains(instance)
        else { throw ForgeError.noInstance(ref.instance) }
        return ForgeProject(instance: instance, projectPath: ref.projectPath)
    }

    /// The end of a job's log (byte range when the instance honours it; the probe result is remembered).
    public func jobLog(_ ref: MergeRequestRef, jobID: Int, maxBytes: Int = MergeRequestService.jobLogBytes) async -> Result<JobLogChunk, ForgeError> {
        do {
            let project = try forgeProject(ref)
            let chunk = try await provider.jobLog(project, jobID: jobID, maxBytes: maxBytes, tryRange: capabilities(ref.instance).support(.jobLogRange).mayTry)
            if let honoured = chunk.rangeHonoured { recordProbe(ref.instance, .jobLogRange, honoured) }
            return .success(chunk)
        } catch {
            return .failure(error as? ForgeError ?? .network(error.localizedDescription))
        }
    }

    /// Loads required approval rules where the instance offers them (Premium/Ultimate); a 404/403 marks the feature
    /// unavailable for the instance so Free instances are not asked again.
    public func loadApprovalRules(_ ref: MergeRequestRef) async {
        guard capabilities(ref.instance).support(.approvalRules).mayTry else { return }
        do {
            approvalRulesStore(ref.url, try await provider.approvalRules(ref))
            recordProbe(ref.instance, .approvalRules, true)
        } catch ForgeError.notFound, ForgeError.forbidden {
            recordProbe(ref.instance, .approvalRules, false)
        } catch {}
    }

    /// Throws unless write actions are on for the instance and the token (when its scopes are known) has `api`.
    public func requireWrites(_ baseURL: String) throws {
        guard settings(for: baseURL).writesEnabled else {
            throw ForgeError.writesDisabled(
                "GitLab write actions are off for \(baseURL). Turn them on in Settings ▸ GitLab (the token then needs the api scope).")
        }
        if instanceStatus[baseURL]?.token?.allowsWrites == false {
            throw ForgeError.writesDisabled(
                "The token for \(baseURL) cannot make changes (its scopes: \(instanceStatus[baseURL]?.token?.scopes?.joined(separator: ", ") ?? "unknown")). Create one with the api scope and choose Replace Token.")
        }
    }

    /// Retries a finished job (the person's action from the panel).
    @discardableResult
    public func retryJob(_ ref: MergeRequestRef, jobID: Int) async throws -> Int? {
        try requireWrites(ref.instance)
        let id = try await provider.retryJob(try forgeProject(ref), jobID: jobID)
        await refresh(ref)
        return id
    }

    /// Plays a manual job (may deploy; the panel confirms first).
    @discardableResult
    public func playJob(_ ref: MergeRequestRef, jobID: Int) async throws -> Int? {
        try requireWrites(ref.instance)
        let id = try await provider.playJob(try forgeProject(ref), jobID: jobID)
        await refresh(ref)
        return id
    }

    /// Approves the MR at the SHA the person reviewed (GitLab refuses if the head moved since).
    public func approve(_ ref: MergeRequestRef, sha: String) async throws {
        try requireApproveAndMerge(ref.instance)
        try await provider.approve(ref, sha: sha)
        await refresh(ref)
    }

    /// Merges at the SHA the person reviewed; GitLab applies every merge check and branch rule.
    public func merge(_ ref: MergeRequestRef, sha: String) async throws {
        try requireApproveAndMerge(ref.instance)
        try await provider.merge(ref, sha: sha)
        await refresh(ref)
    }

    func requireApproveAndMerge(_ baseURL: String) throws {
        try requireWrites(baseURL)
        guard settings(for: baseURL).approveAndMergeEnabled else {
            throw ForgeError.writesDisabled("Approve and Merge are off for \(baseURL) (Settings ▸ GitLab). Only you can use them; agents never can.")
        }
    }
}

// MARK: - Create merge request

/// The title and description BelloCode proposes for a new merge request: generated by the thread's model when the
/// server offers it (`POST /api/session/{id}/generate`), otherwise this template from the branch and its commits.
public enum MergeRequestTemplate {
    /// "feat/launch-checklist" → "Launch checklist"; a single commit's subject wins.
    public static func make(branch: String, commits: [String]) -> (title: String, description: String) {
        let subjects = commits.map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }.filter { !$0.isEmpty }
        let title: String
        if subjects.count == 1 {
            title = subjects[0]
        } else {
            let last = branch.split(separator: "/").last.map(String.init) ?? branch
            let words = last.replacingOccurrences(of: "-", with: " ").replacingOccurrences(of: "_", with: " ").trimmingCharacters(in: .whitespaces)
            title = words.isEmpty ? branch : words.prefix(1).uppercased() + words.dropFirst()
        }
        var description = ""
        if !subjects.isEmpty {
            description = "## Changes\n\n" + subjects.prefix(30).map { "- \($0)" }.joined(separator: "\n")
            if subjects.count > 30 { description += "\n- … and \(subjects.count - 30) more commits" }
        }
        return (String(title.prefix(255)), description)
    }

    /// The prompt for the thread's model. The answer must be a title line, a blank line, then the description.
    public static func prompt(branch: String, target: String, commits: [String]) -> String {
        """
        Write a GitLab merge request title and description for branch \(branch) into \(target). Use what you know of this \
        work from the conversation, if you have one, and its commits.
        Commits:
        \(commits.prefix(40).map { "- \($0)" }.joined(separator: "\n"))
        Answer with the title on the first line (under 72 characters, no prefix), a blank line, then a short Markdown description (what changed and why, how it was tested). Nothing else.
        """
    }

    /// Splits a model answer into title and description (nil when it does not look like one).
    public static func parse(_ answer: String) -> (title: String, description: String)? {
        var lines = answer.trimmingCharacters(in: .whitespacesAndNewlines).components(separatedBy: "\n")
        guard var title = lines.first?.trimmingCharacters(in: .whitespaces), !title.isEmpty else { return nil }
        for prefix in ["Title:", "title:", "# "] where title.hasPrefix(prefix) { title = String(title.dropFirst(prefix.count)).trimmingCharacters(in: .whitespaces) }
        title = title.trimmingCharacters(in: CharacterSet(charactersIn: "\"*`"))
        lines.removeFirst()
        let description = lines.joined(separator: "\n").trimmingCharacters(in: .whitespacesAndNewlines)
        return (String(title.prefix(255)), description)
    }
}

extension MergeRequestService {
    /// Creates the merge request and links it to the thread (only after GitLab acknowledged it).
    public func createMergeRequest(_ draft: MergeRequestDraft, in project: ForgeProject, for thread: SessionID) async throws -> MergeRequestRef {
        guard draft.problems.isEmpty else { throw ExtrasError(draft.problems.joined(separator: " ")) }
        try requireWrites(project.instance.baseURL)
        let ref = try await provider.createMergeRequest(project, draft)
        try await link([ref], to: thread, source: .user)
        await waitForFetches()
        return ref
    }

    /// The MR's changed paths (bounded like `changes`), for Code Owners.
    public func changedPaths(_ ref: MergeRequestRef) async -> [String] {
        ((try? await provider.changes(ref))?.files ?? []).map(\.newPath)
    }

    /// Project info (default branch) for the create form.
    public func projectInfo(_ project: ForgeProject) async throws -> GitLabProjectInfo { try await provider.project(project) }
    public func branches(_ project: ForgeProject, search: String) async throws -> [String] { try await provider.branches(project, search: search) }
    public func users(_ project: ForgeProject, search: String) async throws -> [GitLabUserRef] { try await provider.users(project, search: search) }
}
